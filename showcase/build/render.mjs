// Render showcase videos: headless Chromium (software WebGL) -> JPEG frames -> ffmpeg/libx264 MP4.
//   node showcase/build/render.mjs [video_name ...] [--frames N] [--still i,j,k]
import { spawn } from 'node:child_process';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const require = createRequire(import.meta.url);
let chromium;
try { ({ chromium } = require('playwright')); } catch { ({ chromium } = await import('playwright')); }

const args = process.argv.slice(2);
const opt = { frames: 0, stills: null, crf: 21, q: process.env.SHOWCASE_QUALITY || '' };
const names = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--frames') opt.frames = +args[++i];
  else if (args[i] === '--still') opt.stills = args[++i].split(',').map(Number);
  else if (args[i] === '--crf') opt.crf = +args[++i];
  else names.push(args[i]);
}
const MOT = path.join(HERE, 'cache/motions');
const list = names.length ? names : fs.readdirSync(MOT).filter(n => fs.existsSync(path.join(MOT, n, 'video.json'))).sort();

const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.json': 'application/json', '.bin': 'application/octet-stream' };
const server = http.createServer((req, res) => {
  const p = path.join(HERE, decodeURIComponent(new URL(req.url, 'http://x').pathname));
  if (!p.startsWith(HERE) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'Content-Type': TYPES[path.extname(p)] || 'application/octet-stream' });
  fs.createReadStream(p).pipe(res);
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const port = server.address().port;

const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const outDir = path.join(ROOT, 'showcase/videos');
fs.mkdirSync(outDir, { recursive: true });

for (const name of list) {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(`http://127.0.0.1:${port}/renderer/index.html${opt.q ? '?' + opt.q : ''}`);
  await page.waitForFunction(() => window.SHOWCASE !== undefined);
  const total = await page.evaluate(u => window.SHOWCASE.init(u), `../cache/motions/${name}/video.json`);
  if (errors.length) { console.error(name, errors); process.exitCode = 1; await page.close(); continue; }
  if (opt.stills) {
    for (const f of opt.stills) {
      await page.evaluate(i => window.SHOWCASE.renderFrame(i), f);
      const p = path.join(HERE, 'cache', `still_${name}_${f}.jpg`);
      fs.writeFileSync(p, await page.screenshot({ type: 'jpeg', quality: 90 }));
      console.log('still', p);
    }
    await page.close();
    continue;
  }
  const n = opt.frames || total;
  const out = path.join(outDir, `${name}.mp4`);
  const ff = spawn('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'image2pipe', '-framerate', '30', '-c:v', 'mjpeg', '-i', '-',
    '-c:v', 'libx264', '-preset', 'slow', '-crf', String(opt.crf), '-pix_fmt', 'yuv420p', '-profile:v', 'high',
    '-level', '4.1', '-r', '30', '-movflags', '+faststart', '-metadata',
    `comment=NVIDIA MotionBricks SOMA - real model output generated by showcase/build/generate_motions.py`, out],
    { stdio: ['pipe', 'inherit', 'inherit'] });
  const done = new Promise((res, rej) => ff.on('close', c => (c === 0 ? res() : rej(new Error('ffmpeg ' + c)))));
  const t0 = Date.now();
  let tRender = 0, tShot = 0;
  for (let i = 0; i < n; i++) {
    const a = Date.now();
    await page.evaluate(f => { window.SHOWCASE.renderFrame(f); window.SHOWCASE.sync(); }, i);
    const b = Date.now();
    const jpg = await page.screenshot({ type: 'jpeg', quality: 93 });
    tRender += b - a; tShot += Date.now() - b;
    if (!ff.stdin.write(jpg)) await new Promise(r => ff.stdin.once('drain', r));
  }
  ff.stdin.end();
  await done;
  const mb = fs.statSync(out).size / 1e6;
  console.log(`[render] ${name}: ${n} frames in ${((Date.now() - t0) / 1000).toFixed(0)} s (webgl ${(tRender / n).toFixed(0)} ms/f, capture ${(tShot / n).toFixed(0)} ms/f) -> ${path.relative(ROOT, out)} (${mb.toFixed(1)} MB)`);
  await page.close();
}
await browser.close();
server.close();
