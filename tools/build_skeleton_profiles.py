#!/usr/bin/env python3
"""Write configs/skeletons/soma.yaml from the released checkpoint's skeleton/joints.npy.

joints.npy (NVIDIA Open Model Agreement, part of the HF package) holds the 30 model joints'
rest positions in the standard T-pose relative to the hips; offsets = child - parent.
"""
import sys
from pathlib import Path
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "runtime"))
from somart import contract as C  # noqa: E402

PARENT = {"Hips": None, "Spine1": "Hips", "Spine2": "Spine1", "Chest": "Spine2", "Neck1": "Chest", "Neck2": "Neck1",
          "Head": "Neck2", "Jaw": "Head", "LeftEye": "Head", "RightEye": "Head"}
for s in ("Left", "Right"):
    PARENT.update({f"{s}Shoulder": "Chest", f"{s}Arm": f"{s}Shoulder", f"{s}ForeArm": f"{s}Arm",
                   f"{s}Hand": f"{s}ForeArm", f"{s}HandThumbEnd": f"{s}Hand", f"{s}HandMiddleEnd": f"{s}Hand",
                   f"{s}Leg": "Hips", f"{s}Shin": f"{s}Leg", f"{s}Foot": f"{s}Shin", f"{s}ToeBase": f"{s}Foot"})

src = next((ROOT / "models/soma/original").rglob("vqvae-*/version_0/skeleton/joints.npy"))
pos = np.load(src, allow_pickle=False)
names = list(C.JOINT_NAMES)
offsets = [[0.0, 0.0, 0.0] if PARENT[n] is None else (pos[i] - pos[names.index(PARENT[n])]).round(6).tolist()
           for i, n in enumerate(names)]
prof = {
    "name": "soma", "family": "biped_human", "up_axis": "y",
    "notes": "30 MotionBricks model joints, standard T-pose offsets from the HF checkpoint skeleton/joints.npy "
             "(finger chains collapsed: *HandThumbEnd/*HandMiddleEnd parented to the hand).",
    "hierarchy": [{n: PARENT[n]} for n in names],
    "offsets": offsets,
    "roles": {"pelvis": "Hips", "spine": ["Spine1", "Spine2", "Chest"], "neck": ["Neck1", "Neck2"], "head": "Head",
              "arm_left": ["LeftShoulder", "LeftArm", "LeftForeArm", "LeftHand"],
              "arm_right": ["RightShoulder", "RightArm", "RightForeArm", "RightHand"],
              "leg_left": ["LeftLeg", "LeftShin", "LeftFoot", "LeftToeBase"],
              "leg_right": ["RightLeg", "RightShin", "RightFoot", "RightToeBase"]},
    "contacts": list(C.FOOT_CONTACT_JOINTS), "heading_joints": list(C.HEADING_JOINTS),
}
out = ROOT / "configs/skeletons/soma.yaml"
out.write_text("# Generated by tools/build_skeleton_profiles.py - do not edit by hand\n" + yaml.safe_dump(prof, sort_keys=False))
print("wrote", out, "from", src.relative_to(ROOT))
