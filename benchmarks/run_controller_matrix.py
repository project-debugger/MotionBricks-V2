#!/usr/bin/env python3
"""Run bench_controller.py for every preset + key ablations; write benchmarks/REPORT_controller.md."""
from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY = sys.executable
RUNS = [
    ("ultra_quality", []),
    ("balanced", ["--bvh", "benchmarks/output/balanced_session.bvh"]),
    ("low_vram", []),
    ("extreme_performance", []),
    ("cpu_only", []),
    ("balanced", ["--sync"]),
    ("balanced", ["--no-foot-lock"]),
    ("balanced", ["--set", 'generation.duration_mode="model"']),
    ("balanced", ["--set", "generation.velocity_matching=false", "--no-foot-lock"]),
]


def label(preset, extra):
    tags = []
    if "--sync" in extra:
        tags.append("sync")
    if "--no-foot-lock" in extra:
        tags.append("no foot lock")
    for i, e in enumerate(extra):
        if e == "--set":
            tags.append(extra[i + 1].replace('"', ""))
    return preset + (f" ({', '.join(tags)})" if tags else "")


def mean_std(vals):
    import statistics
    vals = [v for v in vals if v == v]  # drop NaN
    if not vals:
        return float("nan"), 0.0
    return statistics.fmean(vals), (statistics.stdev(vals) if len(vals) > 1 else 0.0)


METRICS = {  # name -> extractor
    "frame_p50": lambda r: r["frame_ms"]["p50"], "frame_p99": lambda r: r["frame_ms"]["p99"],
    "frame_max": lambda r: r["frame_ms"]["max"], "over": lambda r: r["fps"]["frames_over_budget"],
    "cap_avg": lambda r: r["fps"]["avg_capacity"], "cap_p99": lambda r: r["fps"]["min_capacity_p99"],
    "t90": lambda r: r["responsiveness"]["body_t90_mean_s"], "g90": lambda r: r["responsiveness"]["gameplay_t90_mean_s"],
    "track": lambda r: r["tracking_error_m"]["mean"], "slide": lambda r: r["foot_slide_cm_s"],
    "pop": lambda r: r["pop_ratio_p99"], "gps": lambda r: r["generation"]["per_second"],
    "lat": lambda r: r["generation"]["latency_ms"]["p50"], "late": lambda r: r["generation"]["late"],
}


def main() -> int:
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--repeats", type=int, default=3)
    args = ap.parse_args()
    out_dir = ROOT / "benchmarks/results" / ("controller-" + time.strftime("%Y%m%d-%H%M%S"))
    out_dir.mkdir(parents=True, exist_ok=True)
    (ROOT / "benchmarks/output").mkdir(exist_ok=True)
    results = []
    for i, (preset, extra) in enumerate(RUNS):
        reps = []
        for rep in range(args.repeats):
            jp = out_dir / f"run{i}_rep{rep}.json"
            ex = list(extra) + ["--set", f"animation.seed={rep}"]
            if rep and "--bvh" in ex:  # only export the first repeat
                j = ex.index("--bvh"); del ex[j:j + 2]
            cmd = [PY, str(ROOT / "benchmarks/bench_controller.py"), "--preset", preset, "--out", str(jp)] + ex
            p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
            if p.returncode != 0:
                print(p.stderr[-1500:])
                reps = [{"error": p.stderr.strip().splitlines()[-1]}]
                break
            print(p.stdout.strip().splitlines()[-1], flush=True)
            reps.append(json.loads(jp.read_text()))
        if "error" in reps[0]:
            results.append({"label": label(preset, extra), "error": reps[0]["error"]})
            continue
        agg = {k: mean_std([f(r) for r in reps]) for k, f in METRICS.items()}
        results.append({"label": label(preset, extra), "model": reps[0]["model"], "threads": reps[0]["threads"],
                        "repeats": len(reps), "mean_std": agg, "runs": reps})
    (out_dir / "results.json").write_text(json.dumps(results, indent=2))
    (ROOT / "benchmarks/results/latest_controller.json").write_text(json.dumps(results, indent=2))
    L = ["# Real-time controller benchmark\n",
         f"Generated by `benchmarks/run_controller_matrix.py` ({out_dir.name}). Scripted 20 s session at 60 Hz, "
         "real-time paced: idle, run, 90 deg turn, 180 deg reversal, sprint, stop, diagonal walk, crouch, jump, stop. "
         f"Each row: mean +- std over {args.repeats} runs with different target-variation seeds.\n",
         "| configuration | model | frame p50 ms | frame p99 ms | worst ms | frames > 16.7 ms (of 1200) | main-thread FPS "
         "capacity avg / p99 | body t90 s | gameplay t90 s | tracking err m | foot slide cm/s | pop p99 | gens/s | "
         "gen latency p50 ms | late |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]

    def ms(r, k, nd=2):
        m, s_ = r["mean_std"][k]
        return f"{m:.{nd}f} +- {s_:.{nd}f}"

    for r in results:
        if "error" in r:
            L.append(f"| {r['label']} | error: {r['error'][:60]} |")
            continue
        L.append(f"| {r['label']} | {Path(r['model']).stem} (x{r['threads']}) | {ms(r, 'frame_p50')} | "
                 f"{ms(r, 'frame_p99', 1)} | {ms(r, 'frame_max', 1)} | {ms(r, 'over', 1)} | "
                 f"{r['mean_std']['cap_avg'][0]:.0f} / {r['mean_std']['cap_p99'][0]:.0f} | {ms(r, 't90')} | "
                 f"{ms(r, 'g90')} | {ms(r, 'track')} | {ms(r, 'slide', 1)} | {ms(r, 'pop', 1)} | {ms(r, 'gps', 1)} | "
                 f"{ms(r, 'lat', 0)} | {ms(r, 'late', 1)} |")
    L += ["\n## How to read this\n",
          "- *frame* = main-thread cost of `CharacterController.update` per 60 Hz tick (generation runs on a worker thread "
          "unless *sync*). *FPS capacity* = 1000 / frame time: how fast the animation layer alone could tick.",
          "- *body t90* = seconds from an input change until the rendered hips reach 90 % of the commanded velocity "
          "change; *gameplay t90* is the same for the simulated gameplay trajectory (spring-damper). Both use the same "
          "0.25 s smoothing filter, so their difference is the animation lag.",
          "- *tracking err* = mean ground distance between rendered hips and the gameplay trajectory.",
          "- *foot slide* = horizontal foot speed while planted (height + speed contact heuristic, 60 Hz).",
          "- *pop p99* = 99th-percentile joint acceleration / median (spikes = visible pops).",
          "- *late* = results that arrived after their switch frame (hidden by inertialization).",
          "- Generation latency is higher than the isolated model benchmark because the worker shares 4 vCPUs "
          "with the game loop (1 core reserved)."]
    (ROOT / "benchmarks/REPORT_controller.md").write_text("\n".join(L) + "\n")
    print("wrote benchmarks/REPORT_controller.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
